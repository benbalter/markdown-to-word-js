import { describe, it, expect, beforeAll } from 'vitest';
import JSZip from 'jszip';
import mammoth from 'mammoth';
import { convertMarkdownToWord } from '../src/converter';
import { patchDocumentXml } from '../src/docx-font-preset';
import { CHINESE_OFFICIAL_DOC_FONTS } from '../src/font-presets';

const W_NS = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main';

const MARKDOWN = `# 一级标题 Heading 1

正文 with English and 123 digits.

## 二级标题 Heading 2

### 三级标题 Heading 3

#### 四级标题 Heading 4
`;

interface StyleFonts {
  ascii: string | null;
  hAnsi: string | null;
  eastAsia: string | null;
  eastAsiaTheme: string | null;
  sizePt: number | null;
  bold: boolean;
  spacingBeforePt: number | null;
  spacingAfterPt: number | null;
  lineRule: string | null;
  line: string | null;
  firstLine: string | null;
  jc: string | null;
}

function spacingAttr(pPr: Element | undefined, attribute: string): string | null {
  return (
    pPr?.getElementsByTagNameNS(W_NS, 'spacing')[0]?.getAttributeNS(W_NS, attribute) ?? null
  );
}

function spacingPt(pPr: Element | undefined, attribute: 'before' | 'after'): number | null {
  const value = spacingAttr(pPr, attribute);
  return value === null ? null : Number(value) / 20;
}

async function stylesDocument(blob: Blob): Promise<Document> {
  const zip = await JSZip.loadAsync(await blob.arrayBuffer());
  const stylesXml = await zip.file('word/styles.xml')!.async('string');
  return new DOMParser().parseFromString(stylesXml, 'application/xml');
}

function styleOf(
  dom: Document,
  styleId: 'docDefaults' | 'Heading1' | 'Heading2' | 'Heading3' | 'Heading4'
): StyleFonts {
  const scope =
    styleId === 'docDefaults'
      ? dom.getElementsByTagNameNS(W_NS, 'docDefaults')[0]
      : Array.from(dom.getElementsByTagNameNS(W_NS, 'style')).find(
          (style) => style.getAttributeNS(W_NS, 'styleId') === styleId
        )!;
  const rPr = scope.getElementsByTagNameNS(W_NS, 'rPr')[0];
  const pPr = scope.getElementsByTagNameNS(W_NS, 'pPr')[0];
  const rFonts = scope.getElementsByTagNameNS(W_NS, 'rFonts')[0];
  const size = rPr?.getElementsByTagNameNS(W_NS, 'sz')[0]?.getAttributeNS(W_NS, 'val');
  return {
    ascii: rFonts?.getAttributeNS(W_NS, 'ascii') ?? null,
    hAnsi: rFonts?.getAttributeNS(W_NS, 'hAnsi') ?? null,
    eastAsia: rFonts?.getAttributeNS(W_NS, 'eastAsia') ?? null,
    eastAsiaTheme: rFonts?.getAttributeNS(W_NS, 'eastAsiaTheme') ?? null,
    sizePt: size ? Number(size) / 2 : null,
    bold: Array.from(rPr?.children ?? []).some((child) => child.localName === 'b'),
    spacingBeforePt: spacingPt(pPr, 'before'),
    spacingAfterPt: spacingPt(pPr, 'after'),
    lineRule: spacingAttr(pPr, 'lineRule'),
    line: spacingAttr(pPr, 'line'),
    firstLine:
      pPr?.getElementsByTagNameNS(W_NS, 'ind')[0]?.getAttributeNS(W_NS, 'firstLine') ?? null,
    jc: pPr?.getElementsByTagNameNS(W_NS, 'jc')[0]?.getAttributeNS(W_NS, 'val') ?? null,
  };
}

async function documentXml(blob: Blob): Promise<Document> {
  const zip = await JSZip.loadAsync(await blob.arrayBuffer());
  const xml = await zip.file('word/document.xml')!.async('string');
  return new DOMParser().parseFromString(xml, 'application/xml');
}

function attributes(
  element: Element | undefined,
  ...names: string[]
): Record<string, string | null> {
  return Object.fromEntries(
    names.map((name) => [name, element?.getAttributeNS(W_NS, name) ?? null])
  );
}

/** The paragraph whose text is `text`. */
function paragraphWithText(dom: Document, text: string): Element {
  return Array.from(dom.getElementsByTagNameNS(W_NS, 'p')).find(
    (paragraph) =>
      Array.from(paragraph.getElementsByTagNameNS(W_NS, 't'), (t) => t.textContent).join('') ===
      text
  )!;
}

function directIndent(paragraph: Element): string | null {
  const pPr = Array.from(paragraph.children).find((child) => child.localName === 'pPr');
  return pPr?.getElementsByTagNameNS(W_NS, 'ind')[0]?.getAttributeNS(W_NS, 'firstLine') ?? null;
}

describe('default conversion', () => {
  it('leaves the fonts generated by html-to-docx untouched', async () => {
    const dom = await stylesDocument(await convertMarkdownToWord(MARKDOWN));
    const body = styleOf(dom, 'docDefaults');

    expect(body.eastAsia).toBeNull();
    expect(body.eastAsiaTheme).toBe('minorHAnsi');
    expect(styleOf(dom, 'Heading1').eastAsia).toBeNull();
  });

  it('leaves the sizes generated by html-to-docx untouched', async () => {
    const dom = await stylesDocument(await convertMarkdownToWord(MARKDOWN));

    expect(styleOf(dom, 'docDefaults').sizePt).toBe(11);
    expect(styleOf(dom, 'Heading1').sizePt).toBe(24);
  });

  it('leaves the page size, margins and grid generated by html-to-docx untouched', async () => {
    const dom = await documentXml(await convertMarkdownToWord(MARKDOWN));

    expect(attributes(dom.getElementsByTagNameNS(W_NS, 'pgSz')[0], 'w', 'h')).toEqual({
      w: '12240',
      h: '15840',
    });
    expect(dom.getElementsByTagNameNS(W_NS, 'docGrid')).toHaveLength(0);
  });

  it('leaves the paragraph and line spacing generated by html-to-docx untouched', async () => {
    const dom = await stylesDocument(await convertMarkdownToWord(MARKDOWN));
    const body = styleOf(dom, 'docDefaults');

    expect(body.spacingBeforePt).toBeNull();
    expect(body.spacingAfterPt).toBe(6);
    expect(body.lineRule).toBe('atLeast');
    expect(styleOf(dom, 'Heading1').spacingBeforePt).toBe(24);
  });
});

describe('Chinese official document font preset', () => {
  let dom: Document;

  beforeAll(async () => {
    dom = await stylesDocument(
      await convertMarkdownToWord(MARKDOWN, {
        fontPreset: CHINESE_OFFICIAL_DOC_FONTS,
      })
    );
  });

  it('sets FangSong for Chinese body text and Times New Roman for Latin text', () => {
    expect(styleOf(dom, 'docDefaults')).toEqual({
      ascii: 'Times New Roman',
      hAnsi: 'Times New Roman',
      eastAsia: '仿宋',
      eastAsiaTheme: null,
      sizePt: 16,
      bold: false,
      spacingBeforePt: 0,
      spacingAfterPt: 0,
      lineRule: 'exact',
      line: '579',
      firstLine: '640',
      jc: null,
    });
  });

  it('sets exact line spacing at the grid pitch on body text and on every heading level', () => {
    for (const styleId of ['docDefaults', 'Heading1', 'Heading2', 'Heading3', 'Heading4'] as const) {
      expect(styleOf(dom, styleId)).toMatchObject({
        lineRule: 'exact',
        line: '579',
      });
    }
  });

  it('turns widow control off so every full page holds all 22 lines', () => {
    const pPrDefault = dom.getElementsByTagNameNS(W_NS, 'pPrDefault')[0];
    const widowControl = pPrDefault.getElementsByTagNameNS(W_NS, 'widowControl')[0];

    expect(widowControl?.getAttributeNS(W_NS, 'val')).toBe('0');
  });

  it('centers the title without a first-line indent', () => {
    expect(styleOf(dom, 'Heading1')).toMatchObject({
      jc: 'center',
      firstLine: '0',
    });
  });

  it('keeps the two-character indent on the headings below the title', () => {
    for (const styleId of ['Heading2', 'Heading3', 'Heading4'] as const) {
      expect(styleOf(dom, styleId)).toMatchObject({
        jc: null,
        firstLine: '640',
      });
    }
  });

  it('clears paragraph spacing before and after on body text and on every heading level', () => {
    for (const styleId of ['docDefaults', 'Heading1', 'Heading2', 'Heading3', 'Heading4'] as const) {
      expect(styleOf(dom, styleId).spacingBeforePt).toBe(0);
      expect(styleOf(dom, styleId).spacingAfterPt).toBe(0);
    }
  });

  it('sets size 2 for the first level heading and size 3 for the others', () => {
    expect(styleOf(dom, 'Heading1').sizePt).toBe(22);
    expect(styleOf(dom, 'Heading2').sizePt).toBe(16);
    expect(styleOf(dom, 'Heading3').sizePt).toBe(16);
    expect(styleOf(dom, 'Heading4').sizePt).toBe(16);
  });

  it('sets one Chinese font per heading level', () => {
    expect(styleOf(dom, 'Heading1').eastAsia).toBe('方正小标宋简体');
    expect(styleOf(dom, 'Heading2').eastAsia).toBe('黑体');
    expect(styleOf(dom, 'Heading3').eastAsia).toBe('楷体');
    expect(styleOf(dom, 'Heading4').eastAsia).toBe('仿宋');
  });

  it('bolds only the fourth heading level', () => {
    for (const styleId of ['Heading1', 'Heading2', 'Heading3'] as const) {
      expect(styleOf(dom, styleId).bold).toBe(false);
    }
    expect(styleOf(dom, 'Heading4').bold).toBe(true);
  });

  it('keeps every heading font on Times New Roman for Latin characters', () => {
    for (const styleId of ['Heading1', 'Heading2', 'Heading3', 'Heading4'] as const) {
      expect(styleOf(dom, styleId).ascii).toBe('Times New Roman');
      expect(styleOf(dom, styleId).hAnsi).toBe('Times New Roman');
      expect(styleOf(dom, styleId).eastAsiaTheme).toBeNull();
    }
  });

  it('still produces a readable document', async () => {
    const blob = await convertMarkdownToWord(MARKDOWN, {
      fontPreset: CHINESE_OFFICIAL_DOC_FONTS,
    });
    const { value: html } = await mammoth.convertToHtml({
      buffer: Buffer.from(await blob.arrayBuffer()),
    });

    expect(html).toContain('<h1>一级标题 Heading 1</h1>');
    expect(html).toContain('<h4>四级标题 Heading 4</h4>');
    expect(html).toContain('正文 with English and 123 digits.');
  });

  it('preserves the XML declaration of styles.xml', async () => {
    const zip = await JSZip.loadAsync(
      (
        await convertMarkdownToWord(MARKDOWN, {
          fontPreset: CHINESE_OFFICIAL_DOC_FONTS,
        })
      ).arrayBuffer()
    );
    const stylesXml = await zip.file('word/styles.xml')!.async('string');

    expect(stylesXml.startsWith('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>')).toBe(true);
    expect(stylesXml).toContain('<w:styles');
  });
});

describe('Chinese official document page layout', () => {
  const PNG =
    'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';
  const LAYOUT_MARKDOWN = `${MARKDOWN}
| 项目 | 说明 |
| ---- | ---- |
| 甲   | 乙   |

\`\`\`
代码 code
\`\`\`

![图](${PNG})
`;

  let dom: Document;

  beforeAll(async () => {
    dom = await documentXml(
      await convertMarkdownToWord(LAYOUT_MARKDOWN, {
        fontPreset: CHINESE_OFFICIAL_DOC_FONTS,
      })
    );
  });

  it('sets A4 paper and the GB/T 9704 margins', () => {
    expect(attributes(dom.getElementsByTagNameNS(W_NS, 'pgSz')[0], 'w', 'h')).toEqual({
      w: '11906',
      h: '16838',
    });
    expect(
      attributes(dom.getElementsByTagNameNS(W_NS, 'pgMar')[0], 'top', 'right', 'bottom', 'left')
    ).toEqual({ top: '2098', right: '1474', bottom: '1984', left: '1587' });
  });

  it('sets a document grid of 22 lines with 28 characters each', () => {
    // 16838 - 2098 - 1984 = 12756 twips of text height; 12756 / 22 = 579.8.
    // 11906 - 1587 - 1474 = 8845 twips wide: (8845 / 20 / 28 - 16) * 4096 = -841.1, rounded down as Word does.
    expect(
      attributes(dom.getElementsByTagNameNS(W_NS, 'docGrid')[0], 'type', 'linePitch', 'charSpace')
    ).toEqual({ type: 'linesAndChars', linePitch: '579', charSpace: '-842' });
  });

  it('matches the grid Word itself writes for the same page', () => {
    // Word rounds the right margin to 1473 twips and then writes charSpace="-834".
    const xml = `<w:document xmlns:w="${W_NS}"><w:body><w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="2098" w:right="1473" w:bottom="1984" w:left="1587"/></w:sectPr></w:body></w:document>`;

    expect(patchDocumentXml(xml, CHINESE_OFFICIAL_DOC_FONTS).grid).toEqual({
      linePitch: 579,
      charSpace: -834,
    });
  });

  it("drops the generator's per-paragraph line rule so the exact style spacing applies", () => {
    const orphanRules = Array.from(dom.getElementsByTagNameNS(W_NS, 'spacing')).filter(
      (spacing) => spacing.hasAttributeNS(W_NS, 'lineRule') && !spacing.hasAttributeNS(W_NS, 'line')
    );

    expect(orphanRules).toEqual([]);
  });

  it('keeps single spacing on an image paragraph so exact spacing does not crop it', () => {
    const image = dom.getElementsByTagNameNS(W_NS, 'drawing')[0];
    let paragraph = image.parentElement!;
    while (paragraph.localName !== 'p') paragraph = paragraph.parentElement!;

    expect(
      attributes(paragraph.getElementsByTagNameNS(W_NS, 'spacing')[0], 'line', 'lineRule')
    ).toEqual({ line: '240', lineRule: 'auto' });
  });

  it('takes the first-line indent off table cells and code blocks', () => {
    expect(directIndent(paragraphWithText(dom, '甲'))).toBe('0');
    expect(directIndent(paragraphWithText(dom, '代码 code'))).toBe('0');
    expect(directIndent(paragraphWithText(dom, '正文 with English and 123 digits.'))).toBeNull();
  });

  it('lets explicit page margins win, and fits the grid to them', async () => {
    const custom = await documentXml(
      await convertMarkdownToWord(MARKDOWN, {
        fontPreset: CHINESE_OFFICIAL_DOC_FONTS,
        pageMargins: { top: 1, right: 1, bottom: 1, left: 1 },
      })
    );

    expect(attributes(custom.getElementsByTagNameNS(W_NS, 'pgSz')[0], 'w', 'h')).toEqual({
      w: '11906',
      h: '16838',
    });
    expect(
      attributes(custom.getElementsByTagNameNS(W_NS, 'pgMar')[0], 'top', 'right', 'bottom', 'left')
    ).toEqual({ top: '1440', right: '1440', bottom: '1440', left: '1440' });
    // (16838 - 2 * 1440) / 22 = 634.5
    expect(
      custom.getElementsByTagNameNS(W_NS, 'docGrid')[0].getAttributeNS(W_NS, 'linePitch')
    ).toBe('634');
  });
});
